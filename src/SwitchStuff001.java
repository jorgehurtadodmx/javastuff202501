public class SwitchStuff001 {
    public static void main(String[] args) {

        String weather = "suny";

        switch (weather) {
            case "sunny":
                System.out.println("sunnyy");
                break;
            case "windy":
                System.out.println("windyyy");
                break;
            default:
                System.out.println("nada");

        }
    }
}
